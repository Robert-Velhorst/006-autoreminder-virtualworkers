const VA_ID = 41;
const DATE_KEY = "2026-09-25";
const versionOf = (json: string) => createHash("sha256").update(json).digest("hex");

function emptyPlan(detail: string): OperatorDailyPlanPayload {
  return {
    version: 2,
    dateKey: DATE_KEY,
    generatedAt: "2026-09-25T08:00:00.000Z",
    blocks: [],
    robertItems: [],
    unscheduledCards: [],
    planHealth: { confidence: 60, scheduledMinutes: 0, availableMinutes: 540, overlaps: 0, gaps: 540 },
    constraints: { startTime: "09:00", endTime: "18:00", breaks: [] },
    auditTrail: [{ at: "2026-09-25T08:00:00.000Z", action: "saved", detail }],
  };
}

function block(id: string, status: "planned" | "active" | "done" | "skipped", startTime: string, endTime: string) {
  return {
    id,
    startTime,
    endTime,
    cardId: `${id}-card`,
    cardName: id,
    cardUrl: null,
    boardName: "Operations",
    listName: "DOING",
    action: `Work on ${id}`,
    stepIds: [],
    priority: "HIGH",
    score: 100,
    state: "DOING",
    status,
    notes: "",
    flags: [],
  } satisfies OperatorDailyPlanPayload["blocks"][number];
}

