import { randomUUID } from "node:crypto";
import { Client } from "pg";
import { sql } from "drizzle-orm";
import { getTableConfig, PgDialect } from "drizzle-orm/pg-core";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { users } from "../drizzle/schema.postgres";
import { requireIsolatedPostgresTestDatabase } from "../shared/isolatedPostgresTestDatabase.mjs";
import { provisionOwner, type OwnerProvisioningClient } from "./ownerProvisioning";

// Never fall back to operational DATABASE_URL or load an .env file.
const testUrl = process.env.OWNER_PROVISIONING_TEST_DATABASE_URL;
describe.skipIf(!testUrl)("pending owner native PostgreSQL transactions", () => {
  let admin: Client;
  let schemaName: string;
  let connectionString: string;
  const dialect = new PgDialect();
  const options = { username: "synthetic-founder", name: "Synthetic Founder", execute: true };
  const env = () => ({ DATABASE_URL: connectionString, OWNER_BOOTSTRAP_OPEN_ID: options.username,
    OWNER_BOOTSTRAP_TOKEN: "synthetic-bootstrap-token-24-plus" });
  const factory = (): OwnerProvisioningClient => new Client({ connectionString,
    options: `-c search_path=${schemaName}`, connectionTimeoutMillis: 5000 });
  const execute = async (statement: ReturnType<typeof sql>) => {
    const query = dialect.sqlToQuery(statement);
    return admin.query(query.sql, query.params);
  };

  beforeEach(async () => {
    connectionString = requireIsolatedPostgresTestDatabase(testUrl, process.env.NODE_ENV === "production");
    if (new URL(connectionString).pathname !== "/recovery_test") throw new Error("Owner tests require recovery_test.");
    schemaName = `owner_provisioning_${randomUUID().replaceAll("-", "")}`;
    admin = new Client({ connectionString, connectionTimeoutMillis: 5000 });
    await admin.connect();
    await execute(sql`CREATE SCHEMA ${sql.identifier(schemaName)}`);
    await execute(sql`SET search_path TO ${sql.identifier(schemaName)}`);
    // Build an isolated users fixture from canonical column definitions, not a second schema.
    const columns = getTableConfig(users).columns.map(column => sql`${sql.identifier(column.name)}
      ${sql.raw(column.getSQLType())}
      ${column === users.id ? sql`GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY` : sql``}
      ${column.notNull ? sql`NOT NULL` : sql``}
      ${column.default === undefined ? sql`` : sql`DEFAULT ${column.default}`}
      ${column.isUnique ? sql`UNIQUE` : sql``}`);
    await execute(sql`CREATE TABLE ${users} (${sql.join(columns, sql`, `)})`);
  });
  afterEach(async () => {
    if (admin) {
      try {
        if (schemaName) await execute(sql`DROP SCHEMA ${sql.identifier(schemaName)} CASCADE`);
      } finally { await admin.end(); }
    }
  });

  it("dry run leaves no row or consumed sequence; execute and retry preserve a pending owner without VA tables", async () => {
    expect(await provisionOwner({ ...options, execute: false }, env(), factory)).toBe("would-create");
    expect((await admin.query('SELECT count(*)::int AS count FROM users')).rows[0].count).toBe(0);
    expect(await provisionOwner(options, env(), factory)).toBe("created");
    expect(await provisionOwner(options, env(), factory)).toBe("already-pending");
    expect((await admin.query('SELECT id, "openId", role, "passwordHash", "loginMethod" FROM users')).rows)
      .toEqual([{ id: 1, openId: options.username, role: "admin", passwordHash: null, loginMethod: "local" }]);
  });

  it("rolls back an insert when a database trigger fails, then can retry", async () => {
    await admin.query(`CREATE FUNCTION reject_synthetic_owner() RETURNS trigger LANGUAGE plpgsql AS
      $$ BEGIN RAISE EXCEPTION 'synthetic insert rejection'; END $$`);
    await admin.query(`CREATE TRIGGER reject_owner AFTER INSERT ON users FOR EACH ROW EXECUTE FUNCTION reject_synthetic_owner()`);
    await expect(provisionOwner(options, env(), factory)).rejects.toThrow("No success is confirmed");
    expect((await admin.query('SELECT count(*)::int AS count FROM users')).rows[0].count).toBe(0);
    await admin.query('DROP TRIGGER reject_owner ON users');
    expect(await provisionOwner(options, env(), factory)).toBe("created");
  });

  it("serializes two same-owner executions and fails closed for simultaneous different owners", async () => {
    expect((await Promise.all([provisionOwner(options, env(), factory), provisionOwner(options, env(), factory)])).sort())
      .toEqual(["already-pending", "created"]);
    // Clean only this test's disposable schema before exercising the conflicting case.
    await admin.query('DELETE FROM users');
    const results = await Promise.allSettled([
      provisionOwner(options, env(), factory),
      provisionOwner({ ...options, username: "synthetic-other" }, { ...env(), OWNER_BOOTSTRAP_OPEN_ID: "synthetic-other" }, factory),
    ]);
    expect(results.filter(result => result.status === "fulfilled")).toHaveLength(1);
    expect(results.filter(result => result.status === "rejected")).toHaveLength(1);
    expect((await admin.query('SELECT count(*)::int AS count FROM users')).rows[0].count).toBe(1);
  });

  it("waits for ordinary user-table writers and observes their committed conflicting administrator", async () => {
    // Hold an ordinary INSERT lock, without any provisioning-specific advisory protocol.
    await admin.query('BEGIN');
    await admin.query(`INSERT INTO users ("openId", role) VALUES ('synthetic-other-admin', 'admin')`);
    let connected!: () => void;
    const ready = new Promise<void>(resolve => { connected = resolve; });
    const client = factory();
    let settled = false;
    const result = provisionOwner(options, env(), () => { connected(); return client; })
      .then(value => ({ value }), error => ({ error })).finally(() => { settled = true; });
    try {
      await ready;
      const pid = (await admin.query('SELECT pg_backend_pid() AS pid')).rows[0].pid;
      let observed = false;
      for (let attempt = 0; attempt < 100; attempt++) {
        const blocked = await admin.query('SELECT EXISTS (SELECT 1 FROM pg_stat_activity WHERE $1::int = ANY(pg_blocking_pids(pid))) AS blocked', [pid]);
        if (blocked.rows[0].blocked) { observed = true; break; }
        await new Promise(resolve => setTimeout(resolve, 10));
      }
      expect(observed).toBe(true);
      expect(settled).toBe(false);
    } finally { await admin.query('COMMIT'); }
    expect(await result).toMatchObject({ error: { message: expect.stringContaining("different administrator") } });
    expect((await admin.query('SELECT "openId" FROM users')).rows).toEqual([{ openId: "synthetic-other-admin" }]);
  });
});
